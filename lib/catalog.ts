// lib/catalog.ts
// Full 40-category × 100-product deterministic catalog for Worldwide Shopio
// All data is fictional. No real brand assets are used.

export interface CatalogProduct {
  id: string
  sku: string
  name: string
  brand: string
  category: string
  subcategory: string
  price: number
  originalPrice?: number
  discount?: number
  images: string[]
  description: string
  rating: number
  reviews: number
  inStock: boolean
  stock: number
  badge?: string
  tags: string[]
  specs: Record<string, string>
  colors?: string[]
  sizes?: string[]
}

// ── Placeholder image pool (Unsplash/Picsum style via category seeds) ─────────
// We use deterministic picsum.photos URLs keyed by product id seed
function img(seed: number, w = 600, h = 600) {
  return `https://picsum.photos/seed/${seed}/${w}/${h}`
}

// ── Helpers ──────────────────────────────────────────────────────────────────
function lerp(a: number, b: number, t: number) {
  return Math.round(a + (b - a) * t)
}
function pick<T>(arr: T[], seed: number): T {
  return arr[seed % arr.length]
}
function rating(seed: number): number {
  const base = [4.1, 4.2, 4.3, 4.4, 4.5, 4.6, 4.7, 4.8, 4.9, 5.0]
  return pick(base, seed)
}
function reviews(seed: number): number {
  const bases = [12, 24, 38, 55, 71, 88, 103, 146, 204, 312, 450, 682, 891, 1024, 1500]
  return pick(bases, seed * 3)
}
function badge(seed: number, price: number, originalPrice?: number): string | undefined {
  if (originalPrice && originalPrice > price) return 'Sale'
  const b = seed % 10
  if (b === 0) return 'New'
  if (b === 1) return 'Hot'
  if (b === 2) return 'Trending'
  if (b === 3) return 'Limited'
  return undefined
}
function inStock(seed: number): boolean {
  return seed % 12 !== 0
}
function stock(seed: number): number {
  if (!inStock(seed)) return 0
  const opts = [3, 5, 8, 12, 20, 35, 50, 75, 100, 150, 200]
  return pick(opts, seed * 7)
}
function discount(seed: number): number | undefined {
  const discounts = [undefined, undefined, undefined, 5, 10, 15, 20, 25, 30, 40, 50]
  return pick(discounts, seed * 2)
}

