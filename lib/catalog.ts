// ── Product factory ──────────────────────────────────────────────────────────
function makeProducts(cat: CatDef, catIndex: number): CatalogProduct[] {
  const products: CatalogProduct[] = []
  const [adjs, nouns] = cat.nameParts

  for (let i = 0; i < 100; i++) {
    const globalSeed = catIndex * 100 + i
    const adj = adjs[i % adjs.length]
    const noun = nouns[i % nouns.length]
    const brandIndex = (i * 3 + catIndex) % cat.brands.length
    const brand = cat.brands[brandIndex]

    // Vary names to avoid repetition
    const suffix = i < adjs.length ? '' : i < adjs.length * 2 ? ` ${i + 1}` : ` ${brand}`
    const name = `${adj} ${noun}${suffix}`.replace('  ', ' ').trim()

    const [minP, maxP] = cat.priceRange
    const t = ((globalSeed * 17 + 7) % 100) / 100
    const basePrice = Math.round(lerp(minP, maxP, t) * 100) / 100
    const disc = discount(globalSeed)
    const originalPrice = disc ? Math.round(basePrice / (1 - disc / 100)) : undefined
    const price = originalPrice ? basePrice : basePrice

    // Build specs
    const specs: Record<string, string> = {}
    for (const key of cat.specKeys) {
      const vals = cat.specValues[key]
      if (vals) specs[key] = vals[(globalSeed + cat.specKeys.indexOf(key)) % vals.length]
    }

    // 3 images per product
    const imgSeed1 = globalSeed + 1000
    const imgSeed2 = globalSeed + 2000
    const imgSeed3 = globalSeed + 3000

    const tags = [...cat.tags, brand.toLowerCase(), noun.toLowerCase(), adj.toLowerCase()]

    const sku = `WSP-${(catIndex + 1).toString().padStart(2, '0')}-${(i + 1).toString().padStart(4, '0')}`

    products.push({
      id: `cat${catIndex}-prod${i}`,
      sku,
      name,
      brand,
      category: cat.name,
      subcategory: cat.subcategory,
      price,
      originalPrice,
      discount: disc,
      images: [img(imgSeed1), img(imgSeed2), img(imgSeed3)],
      description: `${name} by ${brand}. ${
        cat.name === 'Books'
          ? 'An essential read for anyone passionate about ' +
            noun.toLowerCase() +
            '. Expertly crafted with engaging prose and actionable insights that keep you turning the page.'
          : `A premium ${noun.toLowerCase()} from ${brand}'s flagship ${cat.name} collection. Designed for everyday versatility and lasting quality, crafted with premium materials and expert craftsmanship.`
      }`,
      rating: rating(globalSeed),
      reviews: reviews(globalSeed),
      inStock: inStock(globalSeed),
      stock: stock(globalSeed),
      badge: badge(globalSeed, price, originalPrice),
      tags: [...new Set(tags)],
      specs,
      colors: cat.colors,
      sizes: cat.sizes,
    })
  }
  return products
}

// ── Export full catalog ───────────────────────────────────────────────────────
export const CATALOG: CatalogProduct[] = CATEGORIES.flatMap((cat, i) => makeProducts(cat, i))

export const CATALOG_CATEGORIES = CATEGORIES.map((c) => c.name)

export const CATALOG_CATEGORY_MAP = Object.fromEntries(
  CATEGORIES.map((c, i) => [c.name, CATALOG.slice(i * 100, (i + 1) * 100)]),
)

export function getCatalogProduct(id: string): CatalogProduct | undefined {
  return CATALOG.find((p) => p.id === id)
}

export function searchCatalog(query: string, limit = 50): CatalogProduct[] {
  const q = query.toLowerCase()
  return CATALOG.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.brand.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.tags.some((t) => t.includes(q)),
  ).slice(0, limit)
}
